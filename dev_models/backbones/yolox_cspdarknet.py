def build_backbone(args):
    position_embedding = build_position_encoding(args)
    if args.vit_backbone == 'yolox_cspdarknet_s':
        logger.info(f'build backbone {args.vit_backbone}')
        backbone = CSPDarknet(0.33,0.5)
    elif args.vit_backbone == 'yolox_cspdarknet_myn':
        logger.info(f'build backbone {args.vit_backbone}')
        backbone = CSPDarknet(0.33,0.65)
    else:
        logger.error(f"{args.vit_backbone} not supported")
    if args.num_feature_levels > 1:
        backbone.strides=[8, 16, 32]
        backbone.num_channels = [backbone.base_channels * i for i in [4,8,16]]
    else:
        backbone.out_features=("dark5")
        backbone.strides=[32]
        backbone.num_channels = [backbone.base_channels * 16]
    backbone.init_weights(args.pretrained_path)
    model = Joiner(backbone, position_embedding)
    return model
